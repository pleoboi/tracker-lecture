-- v37 : flux des sorties officielles MANGA Plus en français (toutes séries),
-- affiché dans la Communauté manga. Rempli côté serveur (cron + visite de la
-- page) depuis MangaDex, groupe officiel "MangaPlus". Lecture pour tout membre
-- connecté, écriture réservée au serveur (clé service role, pas de policy).

create table if not exists public.manga_releases (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  mangadex_chapter_id text not null unique,
  mangadex_manga_id text not null,
  anilist_id integer,
  series_title text not null,
  chapter numeric not null,
  chapter_title text,
  url text not null,           -- lien MANGA Plus du chapitre, au même numéro que `chapter`
  cover_url text,
  released_at timestamptz not null
);
create index if not exists idx_manga_releases_released on public.manga_releases (released_at desc);
create index if not exists idx_manga_releases_anilist on public.manga_releases (anilist_id);

alter table public.manga_releases enable row level security;
drop policy if exists "manga_releases_read" on public.manga_releases;
create policy "manga_releases_read" on public.manga_releases
  for select using (auth.role() = 'authenticated');
