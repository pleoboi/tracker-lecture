-- v33 : mode Manga.
-- Tables totalement séparées de books / reading_logs pour que les mangas
-- n'entrent jamais dans les stats, objectifs, Wrapped, badges ou podiums
-- de la partie littérature.
--
-- Une série se lit en chapitres (scans) ou en tomes, au choix à chaque
-- session : la progression est donc suivie sur les deux compteurs
-- (current_chapter / current_volume), et chaque log porte son unité.

create table if not exists public.mangas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null references auth.users (id) on delete cascade,
  title text not null,
  title_native text,
  author text,
  cover_url text,
  anilist_id integer,
  format text,                 -- MANGA, MANHWA, MANHUA, ONE_SHOT, NOVEL... (AniList)
  publication_status text,     -- FINISHED, RELEASING, HIATUS... (AniList)
  total_chapters integer,
  total_volumes integer,
  genres text[],
  published_year integer,
  status text not null default 'reading',
  current_chapter integer not null default 0,
  current_volume integer not null default 0,
  rating numeric(2, 1),
  notes text,
  date_started date,
  date_finished date,
  constraint mangas_status_check
    check (status in ('reading', 'completed', 'to-read', 'paused', 'abandoned')),
  constraint mangas_rating_check
    check (rating is null or (rating >= 0 and rating <= 5))
);

create index if not exists idx_mangas_user on public.mangas (user_id, status);

create table if not exists public.manga_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null references auth.users (id) on delete cascade,
  manga_id bigint not null references public.mangas (id) on delete cascade,
  date date not null default current_date,
  unit text not null,
  amount integer not null,     -- nombre de chapitres / tomes lus pendant la session
  end_value integer not null,  -- chapitre / tome atteint à la fin de la session
  notes text,
  constraint manga_logs_unit_check check (unit in ('chapter', 'volume')),
  constraint manga_logs_amount_check check (amount >= 0)
);

create index if not exists idx_manga_logs_user_date on public.manga_logs (user_id, date);
create index if not exists idx_manga_logs_manga on public.manga_logs (manga_id);

-- RLS : même modèle que books / reading_logs (v2) — chacun écrit chez soi,
-- tout membre connecté peut lire (profils publics).
alter table public.mangas enable row level security;
alter table public.manga_logs enable row level security;

drop policy if exists "mangas_own_all" on public.mangas;
create policy "mangas_own_all" on public.mangas
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "mangas_read_others" on public.mangas;
create policy "mangas_read_others" on public.mangas
  for select
  using (auth.role() = 'authenticated');

drop policy if exists "manga_logs_own_all" on public.manga_logs;
create policy "manga_logs_own_all" on public.manga_logs
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "manga_logs_read_others" on public.manga_logs;
create policy "manga_logs_read_others" on public.manga_logs
  for select
  using (auth.role() = 'authenticated');
